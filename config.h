#pragma once
#include <Arduino.h>

// ============================================================
// 一、引脚（ESP32-C3 Super Mini）
// ============================================================

// TTP223 触摸模块 I/O 输出，摸到 = 高电平。
// 注意：ESP32-C3 深度睡眠只能用 GPIO0~GPIO5 唤醒，触摸脚必须在这个范围内。
#define PIN_TOUCH        5

// 加热 MOS 管 SI2302 的栅极（低边开关），漏极接 MCH 陶瓷加热片。
// 建议栅极到 GND 焊一颗 10k 下拉电阻，保证上电、复位、睡眠时加热片绝对不通电。
#define PIN_HEATER       6

// 电池电压检测：电池正极 → 分压电阻 → 这个 ADC 脚（ADC1_CH3）。
#define PIN_BATTERY_ADC  3

// 可选：第二颗 SI2302 驱动 5V 微型风扇（v1.0 组装指南里的接法）。
#define PIN_FAN          7

// Super Mini 板载蓝色 LED（低电平点亮）。挂件装进毛绒外壳后不一定看得见，只做调试和低电量提示。
#define PIN_LED          8

// ============================================================
// 二、功能开关（1 = 开，0 = 关）
// ============================================================

// 低电量保护。如果你的板子上没有焊电池分压电阻，可以关掉；
// 不关也没关系：读数低于 BATTERY_ABSENT_MV 时程序会认为“没接分压”，自动跳过检测。
#define FEATURE_BATTERY_CHECK  1

// 风扇。v1.1 起量产固件去掉了风扇，纯靠加热片挥发；如果你的硬件装了风扇，改成 1。
#define FEATURE_FAN            0

// 板载 LED 提示（低电量闪烁）。
#define FEATURE_LED            1
#define LED_ACTIVE_LOW         1

// 串口日志（USB CDC，115200）。量产时可以关掉，省一点唤醒时间。
#define FEATURE_SERIAL_LOG     1

// ============================================================
// 三、时序
// ============================================================

// 加热阶段时长：摸一下 = 固定加热这么久，期间不理会触摸，时间到必停。
// 取值说明：v1.5 最后三份源码里这个常量都是 15 s（注释里写的 30 s 是更早的值，已统一）。
constexpr uint32_t HEAT_TIME_MS        = 15UL * 1000UL;

// 强制冷却阶段时长：加热结束后芯片只用定时器唤醒，触摸完全不生效，
// 给加热片散热，也防止连续触摸让香膏过度挥发。
constexpr uint32_t COOLDOWN_TIME_MS    = 20UL * 1000UL;

// 消抖：触摸脚必须连续保持低电平这么久，才算“手指真的松开”，才重新武装触摸唤醒。
constexpr uint32_t TOUCH_STABLE_MS     = 100;

// 进入待机前，最多等手指松开多久。等不到（手指还按着，或 TTP223 处于自锁模式）
// 就改为“等松开再唤醒”，不会卡死，也不会立刻被重新唤醒去加热。
constexpr uint32_t RELEASE_WAIT_MS     = 2000;

// 加热期间多久检查一次电池电压。
constexpr uint32_t BATTERY_POLL_MS     = 500;

// ============================================================
// 四、电池（3.7V 锂电池，TP4056 充电）
// ============================================================

// 分压比 = (R上 + R下) / R下。两颗相同阻值（如 100k + 100k）就是 2.0。
constexpr float    BATTERY_DIVIDER_RATIO = 2.0f;

// 开始加热前电压低于这个值：本次不加热，LED 闪烁提醒去无线充电。
constexpr uint32_t BATTERY_LOW_MV      = 3500;

// 加热过程中（带载）电压掉到这个值以下：立即停止加热，进入冷却。
constexpr uint32_t BATTERY_CUTOFF_MV   = 3300;

// 读数低于这个值，认为分压电阻没焊（ADC 悬空或接地），跳过电量检测。
constexpr uint32_t BATTERY_ABSENT_MV   = 2500;

// ADC 采样次数（取平均，降低噪声）。
constexpr uint8_t  BATTERY_SAMPLES     = 8;

// 低电量时 LED 闪几下。
constexpr uint8_t  LOW_BATTERY_BLINKS  = 3;
